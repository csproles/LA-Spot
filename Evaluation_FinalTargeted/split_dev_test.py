"""PHASE 2 — Patient/lesion-level development vs locked-test split.

Grouping rule: two images are forced into the SAME split if they share a
non-empty patient_id OR a non-empty lesion_id (union-find over both
identifiers at once, so patient-level and lesion-level non-crossing are
both satisfied simultaneously, not as two separate passes that could
contradict each other). Images with neither identifier populated are
treated as their own singleton group — the standard, conservative fallback
when an identifier is unavailable (documented in the cohort report: this
affects the majority of rows, since patient_id is populated for only
42-47% of the cohort).

Target: ~75-80% of each class's IMAGE COUNT in development, ~20-25% in
locked test, allocated by greedily assigning whole GROUPS (never splitting
a group) to test until the class-specific image-count target is reached,
then the rest to development. Malignant-containing groups are handled
first (the rarer, higher-priority class for accurate stratification);
pure-benign groups are handled second.

Fixed seed, documented below. Once written, development_manifest.csv and
locked_test_manifest.csv are not regenerated by this script if they already
exist (refuses to silently overwrite a locked split).
"""

import csv
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COHORT_CSV = ROOT / "Evaluation_FinalTargeted" / "Cohort" / "targeted_cohort_manifest.csv"
OUT_DIR = ROOT / "Evaluation_FinalTargeted" / "Cohort"
DEV_OUT = OUT_DIR / "development_manifest.csv"
TEST_OUT = OUT_DIR / "locked_test_manifest.csv"
REPORT_OUT = OUT_DIR / "split_report.txt"

SEED = 20260918
TEST_FRACTION_TARGET = 0.225  # aim for the middle of the requested 20-25% band


class UnionFind:
    def __init__(self):
        self.parent = {}

    def find(self, x):
        self.parent.setdefault(x, x)
        while self.parent[x] != x:
            self.parent[x] = self.parent[self.parent[x]]
            x = self.parent[x]
        return x

    def union(self, a, b):
        ra, rb = self.find(a), self.find(b)
        if ra != rb:
            self.parent[ra] = rb


def build_groups(rows):
    uf = UnionFind()
    for r in rows:
        img_key = ("img", r["image_id"])
        uf.find(img_key)
        if r["patient_id"].strip():
            uf.union(img_key, ("pat", r["patient_id"]))
        if r["lesion_id"].strip():
            uf.union(img_key, ("les", r["lesion_id"]))

    groups = {}
    for r in rows:
        root = uf.find(("img", r["image_id"]))
        groups.setdefault(root, []).append(r)
    return list(groups.values())


def greedy_assign_to_test(groups, target_test_count, rng):
    """Shuffle groups, then add whole groups to test until the running
    malignant-image count (for malignant-containing groups) or benign-image
    count (for pure-benign groups) reaches target. Returns (test_rows, dev_rows)."""
    groups = list(groups)
    rng.shuffle(groups)
    test_rows, dev_rows = [], []
    running = 0
    for g in groups:
        if running < target_test_count:
            test_rows.extend(g)
            running += len(g)
        else:
            dev_rows.extend(g)
    return test_rows, dev_rows


def main():
    if DEV_OUT.exists() or TEST_OUT.exists():
        raise SystemExit(
            f"Refusing to overwrite an existing split ({DEV_OUT.name} / {TEST_OUT.name} already "
            f"present). The dev/test split is locked once created. Delete both files manually "
            f"first if a genuinely new split is intended."
        )

    with open(COHORT_CSV, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    fieldnames = list(rows[0].keys())
    print(f"Loaded {len(rows)} cohort rows")

    groups = build_groups(rows)
    n_singleton = sum(1 for g in groups if len(g) == 1)
    n_multi = len(groups) - n_singleton
    print(f"Grouped into {len(groups)} groups ({n_singleton} singleton, {n_multi} multi-image)")

    mal_groups = [g for g in groups if any(r["ground_truth"] == "malignant" for r in g)]
    ben_groups = [g for g in groups if all(r["ground_truth"] == "benign" for r in g)]
    n_mal_total = sum(1 for r in rows if r["ground_truth"] == "malignant")
    n_ben_total = sum(1 for r in rows if r["ground_truth"] == "benign")

    rng = random.Random(SEED)
    mal_test_rows, mal_dev_rows = greedy_assign_to_test(
        mal_groups, round(n_mal_total * TEST_FRACTION_TARGET), rng
    )
    ben_test_rows, ben_dev_rows = greedy_assign_to_test(
        ben_groups, round(n_ben_total * TEST_FRACTION_TARGET), rng
    )

    # a malignant-containing group can include benign rows too (mixed-class
    # patient/lesion group) — count both classes actually landing in test
    test_rows = mal_test_rows + ben_test_rows
    dev_rows = mal_dev_rows + ben_dev_rows

    with open(DEV_OUT, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames); w.writeheader(); w.writerows(dev_rows)
    with open(TEST_OUT, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames); w.writeheader(); w.writerows(test_rows)

    # verify no group/patient/lesion crosses the split
    dev_ids = {r["image_id"] for r in dev_rows}
    test_ids = {r["image_id"] for r in test_rows}
    dev_patients = {r["patient_id"] for r in dev_rows if r["patient_id"].strip()}
    test_patients = {r["patient_id"] for r in test_rows if r["patient_id"].strip()}
    dev_lesions = {r["lesion_id"] for r in dev_rows if r["lesion_id"].strip()}
    test_lesions = {r["lesion_id"] for r in test_rows if r["lesion_id"].strip()}
    patient_overlap = dev_patients & test_patients
    lesion_overlap = dev_lesions & test_lesions
    image_overlap = dev_ids & test_ids

    n_dev_mal = sum(1 for r in dev_rows if r["ground_truth"] == "malignant")
    n_dev_ben = sum(1 for r in dev_rows if r["ground_truth"] == "benign")
    n_test_mal = sum(1 for r in test_rows if r["ground_truth"] == "malignant")
    n_test_ben = sum(1 for r in test_rows if r["ground_truth"] == "benign")

    report = [
        "PHASE 2 — DEVELOPMENT / LOCKED-TEST SPLIT REPORT",
        "=" * 50,
        f"Seed: {SEED}   Target test fraction: {TEST_FRACTION_TARGET:.1%}",
        f"Grouping: union of shared patient_id and/or lesion_id; missing identifiers "
        f"treated as unique singleton groups ({n_singleton}/{len(groups)} groups are singletons)",
        "",
        f"Total cohort: {len(rows)}",
        f"Development: {len(dev_rows)} ({100*len(dev_rows)/len(rows):.1f}%)  "
        f"— malignant={n_dev_mal}, benign={n_dev_ben}",
        f"Locked test: {len(test_rows)} ({100*len(test_rows)/len(rows):.1f}%)  "
        f"— malignant={n_test_mal}, benign={n_test_ben}",
        "",
        f"INTEGRITY CHECKS:",
        f"  image_id overlap between dev/test:   {len(image_overlap)} (must be 0)",
        f"  patient_id overlap between dev/test:  {len(patient_overlap)} (must be 0)",
        f"  lesion_id overlap between dev/test:   {len(lesion_overlap)} (must be 0)",
    ]
    report_text = "\n".join(report)
    print("\n" + report_text)
    with open(REPORT_OUT, "w", encoding="utf-8") as f:
        f.write(report_text)

    if image_overlap or patient_overlap or lesion_overlap:
        raise SystemExit("CRITICAL: split integrity check failed — patient/lesion/image crossed "
                         "the dev/test boundary. This is a stop-condition; halting before any "
                         "further phase runs on a contaminated split.")


if __name__ == "__main__":
    main()
